#!/bin/sh
#
# Test for the Site Build feature (prompts/features/01-site-build.md).
# The build script runs against a temporary directory so that generated
# output never lands in the repository tree.
# Verifies the summary page builds without live state, and the dashboard
# substitutes state values when the state file is present and renders
# "unavailable" when it is absent.
set -eu

DIRECTORY_SCRIPT=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
REPOSITORY_ROOT=$(CDPATH= cd -- "$DIRECTORY_SCRIPT/.." && pwd)
SCRIPT_BUILD="$REPOSITORY_ROOT/scripts/site-build.sh"

if grep -q '<html>' "$SCRIPT_BUILD"; then
    echo '04-site-build: build script embeds HTML structure' >&2
    exit 1
fi

DIRECTORY_TEMPORARY=$(mktemp -d)
trap 'rm -rf "$DIRECTORY_TEMPORARY"' EXIT HUP INT TERM

mkdir -p "$DIRECTORY_TEMPORARY/in"
cp "$REPOSITORY_ROOT/site.in/template.html" "$DIRECTORY_TEMPORARY/in/template.html"

printf '%s\n' '<h1>Summary</h1>' > "$DIRECTORY_TEMPORARY/in/index.txt"
printf '%s\n' '<p>Branch __BRANCH__, tiles __ETOPO_FILES__</p>' > "$DIRECTORY_TEMPORARY/in/dashboard.txt"

# Build without a state file: summary builds; dashboard shows unavailable.
SITE_STATE_FILE="$DIRECTORY_TEMPORARY/no-such-state.txt" \
    sh "$SCRIPT_BUILD" "$DIRECTORY_TEMPORARY/in" "$DIRECTORY_TEMPORARY/out" >/dev/null

FILE_SUMMARY="$DIRECTORY_TEMPORARY/out/index.html"
FILE_DASHBOARD="$DIRECTORY_TEMPORARY/out/dashboard.html"

grep -q '<!DOCTYPE html>' "$FILE_SUMMARY" || {
    echo '04-site-build: summary is missing the doctype' >&2
    exit 1
}

grep -q '<title>Global Elevation Model Dataset</title>' "$FILE_SUMMARY" || {
    echo '04-site-build: summary is missing the mapped title' >&2
    exit 1
}

grep -q 'generated by scripts/site-build.sh' "$FILE_SUMMARY" || {
    echo '04-site-build: summary is missing the generated-file marker' >&2
    exit 1
}

grep -q 'unavailable' "$FILE_DASHBOARD" || {
    echo '04-site-build: dashboard without state must render unavailable' >&2
    exit 1
}

# Build with a state file: dashboard substitutes the values.
printf '%s\n' 'BRANCH=master' 'ETOPO_FILES=350' > "$DIRECTORY_TEMPORARY/state.txt"

SITE_STATE_FILE="$DIRECTORY_TEMPORARY/state.txt" \
    sh "$SCRIPT_BUILD" "$DIRECTORY_TEMPORARY/in" "$DIRECTORY_TEMPORARY/out" >/dev/null

grep -q 'Branch master' "$FILE_DASHBOARD" || {
    echo '04-site-build: dashboard did not substitute BRANCH' >&2
    exit 1
}

grep -q 'tiles 350' "$FILE_DASHBOARD" || {
    echo '04-site-build: dashboard did not substitute ETOPO_FILES' >&2
    exit 1
}

grep -q 'unavailable' "$FILE_DASHBOARD" && {
    echo '04-site-build: dashboard still shows unavailable with a state file' >&2
    exit 1
}

echo '04-site-build: ok'
exit 0
